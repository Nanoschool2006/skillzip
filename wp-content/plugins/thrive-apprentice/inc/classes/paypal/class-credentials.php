	/**
	 * Map a capability item's vetting sub-state to a seller-facing phase.
	 *
	 * Maps PayPal's documented `vetting_status` enum (Partner Referrals v1 Product schema:
	 * APPROVED, PENDING, DECLINED, SUBSCRIBED, IN_REVIEW, NEED_MORE_DATA, DENIED) to a phase,
	 * with `capability_status` as a fallback signal. Unknown values return '' (no notice) so a
	 * benign/unrecognized state never raises a false action-required banner.
	 *
	 * @param array $vetting { vetting_status, capability_status, limits }
	 * @return string '' | 'approved' | 'in_review' | 'needs_info' | 'denied'
	 */
	public static function vetting_phase( array $vetting ): string {
		$vs = strtoupper( (string) ( $vetting['vetting_status'] ?? '' ) );
		$cs = strtoupper( (string) ( $vetting['capability_status'] ?? '' ) );

		if ( $cs === 'DENIED' || in_array( $vs, [ 'DENIED', 'DECLINED' ], true ) ) {
			return 'denied';
		}
		// Conservative: only an explicit NEED_MORE_DATA fires the action banner.
		// `limits` alone does NOT — SUBSCRIBED_WITH_LIMIT-style states are often
		// benign, and a false action-required banner is worse than a missed one.
		if ( $vs === 'NEED_MORE_DATA' ) {
			return 'needs_info';
		}
		if ( in_array( $vs, [ 'SUBSCRIBED', 'APPROVED' ], true ) || $cs === 'ACTIVE' ) {
			return 'approved';
		}
		if ( in_array( $cs, [ 'PENDING', 'IN_REVIEW' ], true ) || in_array( $vs, [ 'IN_REVIEW', 'PENDING' ], true ) ) {
			return 'in_review';
		}
		return '';
	}

	/**
	 * Capability items whose vetting needs seller attention (needs_info/denied),
	 * for the admin action banner. In-review is intentionally excluded (shown as a pill).
	 *
	 * @param string|null $mode 'live', 'test' or null for auto.
	 * @return array<int,array{key:string,label:string,phase:string}>
	 */
	public static function get_vetting_alerts( $mode = null ): array {
		$alerts = [];
		foreach ( static::get_capabilities_summary( $mode )['groups'] as $group ) {
			foreach ( (array) ( $group['items'] ?? [] ) as $item ) {
				if ( empty( $item['vetting'] ) || ! is_array( $item['vetting'] ) ) {
					continue;
				}
				$phase = static::vetting_phase( $item['vetting'] );
				if ( in_array( $phase, [ 'needs_info', 'denied' ], true ) ) {
					$alerts[] = [
						'key'   => $item['key'] ?? '',
						'label' => $item['label'] ?: ( $item['key'] ?? '' ),
						'phase' => $phase,
					];
				}
			}
		}
		return $alerts;
	}

	/**
	 * Remove all PayPal credential options from wp_options.
	 *
	 * IMPORTANT — this method only clears credentials; it does NOT cancel subscriptions.
	 * The D17 subscription wind-down (cancel each active vault subscription at period end)
	 * is performed by Subscription_Winddown::run(), which MUST be called BEFORE this method
	 * while the bearer token is still live. Once credentials are
	 * gone the cancel calls would fail and any renewal webhooks would be silently dropped
	 * (the webhook secret is cleared below), leaving subscribers billed with no order or
	 * access update recorded.
	 *
	 * The admin-initiated disconnect endpoint runs the wind-down first; the admin UI warns
	 * the merchant beforehand, showing the count of active/grace-period subscriptions.
	 */
	public static function disconnect() {
		// New flow options
		static::delete_state();
		static::delete_state_live();
		delete_option( static::SITE_SECRET_OPTION );
		delete_option( static::SITE_SECRET_OPTION_LIVE );
		delete_option( static::REFERRAL_TOKEN_OPTION );
		delete_option( static::REFERRAL_TOKEN_OPTION_LIVE );
		delete_option( static::CLIENT_ID_OPTION );
		delete_option( static::CLIENT_ID_OPTION_LIVE );
		delete_option( static::SDK_TOKEN_OPTION );
		delete_option( static::SDK_TOKEN_OPTION_LIVE );
		delete_option( static::WEBHOOK_SECRET_OPTION );
		delete_option( static::WEBHOOK_SECRET_OPTION_LIVE );
		delete_option( static::MERCHANT_ID_OPTION );
		delete_option( static::MERCHANT_ID_OPTION_LIVE );
		delete_option( static::COUNTRY_OPTION );
		delete_option( static::COUNTRY_OPTION_LIVE );
		delete_option( static::CREDENTIALS_ENDPOINT_OPTION );
		delete_option( static::CREDENTIALS_ENDPOINT_OPTION_LIVE );
		// Bearer token transients
		foreach ( [ 'onboarding', 'order', 'vault' ] as $client ) {
			foreach ( [ 'live', 'test' ] as $mode ) {
				delete_transient( \TVA\PayPal\Http\Base_Client::make_transient_key( $client, $mode ) );
			}
		}
		// Legacy OAuth options (migration safety for existing installs)
		delete_option( static::ACCESS_TOKEN_OPTION );
		delete_option( static::ACCESS_TOKEN_OPTION_LIVE );
		delete_option( static::REFRESH_TOKEN_OPTION );
		delete_option( static::REFRESH_TOKEN_OPTION_LIVE );
		delete_option( static::EXPIRES_AT_OPTION );
		delete_option( static::EXPIRES_AT_OPTION_LIVE );
		delete_option( static::CAPABILITIES_OPTION );      // raw per-mode cache (test)
		delete_option( static::CAPABILITIES_OPTION_LIVE ); // raw per-mode cache (live)
		delete_option( static::CAPABILITIES_SUMMARY_OPTION );
		delete_option( static::CAPABILITIES_SUMMARY_OPTION_LIVE );
		delete_option( static::VETTING_STATUS_OPTION );
		delete_option( static::VETTING_STATUS_OPTION_LIVE );
		delete_option( static::EMAIL_CONFIRMED_OPTION );
		delete_option( static::EMAIL_OPTION );
		delete_option( static::EMAIL_OPTION_LIVE );
		delete_option( static::PAYMENTS_RECEIVABLE_OPTION );
		delete_option( static::LIVE_COUNT_OPTION );
		delete_option( static::TEST_COUNT_OPTION );
		Settings::reset();
		// Invalidate any per-request caches held by Connection (no-op after #3769,
		// kept so future additions to Connection::reset() take effect automatically).
		Connection::reset();
		// Drop Apple Pay domain state (static file + records) so a reconnecting
		// merchant doesn't inherit the previous account's registration/file.
		\TVA\PayPal\Apple_Pay::uninstall();
	}

