	/**
	 * Get (or lazily create) the credentials endpoint slug.
	 *
	 * Stored in wp_options with autoload = false. The slug becomes part of the
	 * REST URL PayPal redirects back to after OAuth — kept stable across requests.
	 *
	 * @param string $mode 'live' or 'test'
	 *
	 * @return string
	 */
	public static function get_credentials_endpoint( $mode = 'live' ) {
		$option_name = $mode === 'live'
			? static::CREDENTIALS_ENDPOINT_OPTION_LIVE
			: static::CREDENTIALS_ENDPOINT_OPTION;

		$endpoint = get_option( $option_name, false );

		if ( ! $endpoint ) {
			$endpoint = static::generate_endpoint_slug();
			update_option( $option_name, $endpoint, false );
			static::clear_object_cache( $option_name );
		}

		return $endpoint;
	}

	/**
	 * Generate a 16-char endpoint slug, preferring the CSPRNG.
	 *
	 * random_bytes() can throw on entropy/OS failure. This slug is generated lazily during
	 * REST route registration (TVA_PayPal_Controller::register_routes()), where an uncaught
	 * throw would fatal route setup and leave the PayPal gateway with no endpoints at all —
	 * including the webhook listener. Fall back to wp_generate_password() (backed by wp_rand)
	 * so slug generation can never fatal a request.
	 *
	 * @return string 16-character slug.
	 */
	protected static function generate_endpoint_slug() {
		try {
			return bin2hex( random_bytes( 8 ) ); // 16-char hex, CSPRNG
		} catch ( \Throwable $e ) {
			return strtolower( wp_generate_password( 16, false, false ) );
		}
	}

	/**
	 * Generate a cryptographically random state token for OAuth CSRF protection.
	 *
	 * @return string 80-character padded hex string
	 * @throws RandomException
	 */
	public static function generate_state() {
		$pad = substr( uniqid( 'paypal-', true ), 0, 20 );

		return str_pad( bin2hex( random_bytes( 16 ) ), 80, $pad, STR_PAD_BOTH );
	}

