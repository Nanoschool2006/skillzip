	/**
	 * Return the buyer's stored PayPal customer id for the given mode.
	 *
	 * PayPal mints a customer.id the first time a buyer vaults a method; we store it
	 * per WP user so subsequent vaults attach to the same PayPal customer.
	 *
	 * @param int    $user_id WP user id.
	 * @param string $mode    'live' or 'test'.
	 * @return string Stored customer id, or '' when none / no user.
	 */
	public static function get_customer_id( $user_id, $mode = 'live' ) {
		$user_id = (int) $user_id;
		if ( $user_id <= 0 ) {
			return '';
		}
		return (string) get_user_meta( $user_id, 'tva_paypal_customer_id_' . $mode, true );
	}

	/**
	 * Store the buyer's PayPal customer id for the given mode. Write-once: an existing
	 * non-empty value is never overwritten (PayPal keeps the same customer for a buyer).
	 *
	 * @param int    $user_id WP user id.
	 * @param string $id      PayPal customer id.
	 * @param string $mode    'live' or 'test'.
	 */
	public static function save_customer_id( $user_id, $id, $mode = 'live' ) {
		$user_id = (int) $user_id;
		$id      = sanitize_text_field( (string) $id );
		if ( $user_id <= 0 || $id === '' ) {
			return;
		}
		if ( static::get_customer_id( $user_id, $mode ) !== '' ) {
			return;
		}
		// Write-once, so a false return here is a real failure (not an unchanged value): this is
		// the buyer's vault-customer anchor, so surface it in the log rather than failing silently.
		if ( false === update_user_meta( $user_id, 'tva_paypal_customer_id_' . $mode, $id ) ) {
			\TVA_Logger::set_type( 'PayPal' );
			\TVA_Logger::log( 'customer_id_store_failed', [ 'user_id' => $user_id, 'mode' => $mode ], true );
		}
	}

