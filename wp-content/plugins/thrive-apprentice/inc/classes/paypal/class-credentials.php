	/**
	 * Persist the Product API's capabilities_summary block for a mode.
	 * Rejects unknown schema versions so a contract change can't poison the UI;
	 * whitelists the fields the admin grid consumes.
	 *
	 * Note: `extra` values are sanitized recursively — nested structure and
	 * scalar types (bool/int/float) are preserved; string leaves are sanitized.
	 *
	 * @param array  $summary Decoded capabilities_summary from GET /merchant.
	 * @param string $mode    'live' or 'test' (required; no default).
	 *
	 * @return bool Whether the summary was accepted and stored.
	 */
	public static function save_capabilities_summary( array $summary, string $mode ) {
		if ( (int) ( $summary['schema_version'] ?? 0 ) !== 1 ) {
			if ( defined( 'WP_DEBUG' ) && WP_DEBUG ) {
				error_log( sprintf(
					'TVA PayPal: rejected capabilities_summary with schema_version %s (only 1 is supported) — keeping the previously stored summary.',
					wp_json_encode( $summary['schema_version'] ?? null )
				) );
			}

			return false;
		}

		$clean = [ 'groups' => [], 'rollup' => [] ];

		foreach ( (array) ( $summary['groups'] ?? [] ) as $group ) {
			if ( empty( $group['key'] ) ) {
				continue;
			}
			$clean_group = [
				'key'   => sanitize_key( $group['key'] ),
				'label' => sanitize_text_field( $group['label'] ?? '' ),
				'items' => [],
			];
			foreach ( (array) ( $group['items'] ?? [] ) as $item ) {
				if ( empty( $item['key'] ) ) {
					continue;
				}
				$clean_item = [
					'key'        => sanitize_key( $item['key'] ),
					'label'      => sanitize_text_field( $item['label'] ?? '' ),
					'status'     => strtoupper( sanitize_text_field( $item['status'] ?? '' ) ),
					'renderable' => ! empty( $item['renderable'] ),
				];
				if ( ! empty( $item['extra'] ) && is_array( $item['extra'] ) ) {
					$clean_item['extra'] = static::sanitize_extra( $item['extra'] );
				}
				if ( ! empty( $item['vetting'] ) && is_array( $item['vetting'] ) ) {
					$clean_item['vetting'] = [
						'vetting_status'    => strtoupper( sanitize_text_field( $item['vetting']['vetting_status'] ?? '' ) ),
						'capability_status' => strtoupper( sanitize_text_field( $item['vetting']['capability_status'] ?? '' ) ),
						'limits'            => static::sanitize_extra( (array) ( $item['vetting']['limits'] ?? [] ) ),
					];
				}
				$clean_group['items'][] = $clean_item;
			}
			$clean['groups'][] = $clean_group;
		}

		$rollup          = (array) ( $summary['rollup'] ?? [] );
		$clean['rollup'] = [
			'all_ready'        => ! empty( $rollup['all_ready'] ),
			'any_pending'      => ! empty( $rollup['any_pending'] ),
			'renderable_count' => (int) ( $rollup['renderable_count'] ?? 0 ),
			'pending'          => array_map( 'sanitize_key', (array) ( $rollup['pending'] ?? [] ) ),
			'missing'          => array_map( 'sanitize_key', (array) ( $rollup['missing'] ?? [] ) ),
		];

		$option = $mode === 'live' ? static::CAPABILITIES_SUMMARY_OPTION_LIVE : static::CAPABILITIES_SUMMARY_OPTION;
		update_option( $option, $clean, false );

		return true;
	}

	/**
	 * Recursively sanitize a summary item's `extra` metadata, preserving the
	 * nested structure and scalar types: bool/int/float pass through unchanged
	 * (so the localized JS payload keeps real booleans), strings are sanitized.
	 *
	 * @param array $extra
	 *
	 * @return array
	 */
	private static function sanitize_extra( array $extra ) {
		$clean = [];
		foreach ( $extra as $key => $value ) {
			$key = sanitize_key( $key );
			if ( is_array( $value ) ) {
				$clean[ $key ] = static::sanitize_extra( $value );
			} elseif ( is_bool( $value ) || is_int( $value ) || is_float( $value ) ) {
				$clean[ $key ] = $value;
			} else {
				$clean[ $key ] = sanitize_text_field( (string) $value );
			}
		}

		return $clean;
	}

	/**
	 * Stored capabilities_summary for a mode. Defaults to the live summary when
	 * live is connected, the test one otherwise (mirrors which connection the
	 * settings page treats as primary).
	 *
	 * @param string|null $mode 'live', 'test' or null for auto.
	 *
	 * @return array{groups:array,rollup:array}
	 */
	public static function get_capabilities_summary( $mode = null ) {
		if ( $mode === null ) {
			$mode = static::is_mode_enabled( 'live' ) ? 'live' : 'test';
		}

		$option = $mode === 'live' ? static::CAPABILITIES_SUMMARY_OPTION_LIVE : static::CAPABILITIES_SUMMARY_OPTION;
		$stored = get_option( $option, [] );

		if ( ! is_array( $stored ) || empty( $stored['groups'] ) ) {
			return [ 'groups' => [], 'rollup' => [] ];
		}

		return [
			'groups' => (array) $stored['groups'],
			'rollup' => (array) ( $stored['rollup'] ?? [] ),
		];
	}

	/**
	 * Keys of the buyer-facing (renderable) items across all summary groups —
	 * the only keys the checkout-method display toggles accept. The contract
	 * guarantees renderable implies ACTIVE; the status check makes a contract
	 * violation fail closed for every consumer (toggles, REST, JS payload).
	 *
	 * @param string|null $mode 'live', 'test' or null for auto.
	 *
	 * @return string[]
	 */
	public static function get_renderable_keys( $mode = null ) {
		$keys = [];
		foreach ( static::get_capabilities_summary( $mode )['groups'] as $group ) {
			foreach ( (array) ( $group['items'] ?? [] ) as $item ) {
				if ( ! empty( $item['renderable'] ) && ! empty( $item['key'] ) && ( $item['status'] ?? '' ) === 'ACTIVE' ) {
					$keys[] = $item['key'];
				}
			}
		}

		return array_values( array_unique( $keys ) );
	}

