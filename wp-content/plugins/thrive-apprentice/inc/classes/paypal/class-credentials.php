	/**
	 * Normalise an expiry value to an ISO-8601 string.
	 *
	 * PayPal OAuth responses may send expires_at as an ISO string ("2027-01-01T00:00:00Z")
	 * or as a Unix integer. Storing always as ISO-8601 keeps strtotime() reliable.
	 *
	 * @param string|int $expires_at
	 *
	 * @return string
	 */
	public static function normalise_expires_at( $expires_at ) {
		if ( is_numeric( $expires_at ) ) {
			return gmdate( 'Y-m-d\TH:i:s\Z', (int) $expires_at );
		}

		return (string) $expires_at;
	}

	/**
	 * Persist all credential values for one mode at once.
	 *
	 * expires_at is normalised to ISO-8601 before storage.
	 *
	 * @param string     $access_token
	 * @param string     $refresh_token
	 * @param string|int $expires_at    ISO 8601 string or Unix timestamp integer
	 * @param string     $mode          'live' or 'test'
	 * @param string     $merchant_id
	 *
	 * @return bool
	 */
	public static function save_credentials( $access_token, $refresh_token, $expires_at, $mode, $merchant_id ) {
		$normalised_expiry = static::normalise_expires_at( $expires_at );

		if ( $mode === 'live' ) {
			update_option( static::ACCESS_TOKEN_OPTION_LIVE, $access_token, false );
			update_option( static::REFRESH_TOKEN_OPTION_LIVE, $refresh_token, false );
			update_option( static::EXPIRES_AT_OPTION_LIVE, $normalised_expiry, false );
			static::save_account_id_live( $merchant_id );
			static::delete_state_live();
		} else {
			update_option( static::ACCESS_TOKEN_OPTION, $access_token, false );
			update_option( static::REFRESH_TOKEN_OPTION, $refresh_token, false );
			update_option( static::EXPIRES_AT_OPTION, $normalised_expiry, false );
			static::save_account_id( $merchant_id );
			static::delete_state();
		}

		return true;
	}

