	/**
	 * Number of Thrive Apprentice products that have a PayPal price configured.
	 *
	 * Computed dynamically by scanning products for a PayPal pricing rule (same
	 * approach as Square's get_protected_products_count) rather than reading a
	 * stored counter, which was never maintained. PayPal pricing rules are not
	 * mode-specific, so the count is attributed to the currently-connected mode;
	 * the other mode reports 0.
	 *
	 * @param bool $live
	 *
	 * @return int
	 */
	public static function get_protected_products_count( $live = true ) {
		$mode = $live ? 'live' : 'test';

		if ( ! static::is_mode_enabled( $mode ) ) {
			return 0;
		}

		$products = \TVA\Product::get_items();
		$products = ( is_array( $products ) || is_object( $products ) ) ? $products : [];

		$count = 0;
		foreach ( $products as $product ) {
			// TVA\Product defines __get() but not __isset(), so isset( $product->ID )
			// is always false; read the id via the canonical accessor instead.
			$product_id = (int) $product->get_id();
			if ( $product_id <= 0 ) {
				continue;
			}

			$rule = Settings::get_product_rule( $product_id );
			if ( ! empty( $rule['amount'] ) && ! empty( $rule['currency'] ) ) {
				$count++;
			}
		}

		return $count;
	}

